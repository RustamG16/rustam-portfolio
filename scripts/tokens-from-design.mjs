// DESIGN.md front-matter (normative) -> src/styles/tokens.css (executable copy).
// Run: node scripts/tokens-from-design.mjs   (npm run tokens)
// Amendments go DESIGN.md -> tokens.css -> design.json -> code. Never hand-edit tokens.css.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const md = fs.readFileSync(path.join(root, 'DESIGN.md'), 'utf8').replace(/\r\n/g, '\n');
const fm = yaml.load(md.match(/^---\n([\s\S]*?)\n---\n/)[1]);

const need = (v, what) => {
  if (v === undefined || v === null) throw new Error(`DESIGN.md is missing ${what}`);
  return v;
};
const ty = (k) => need(fm.typography[k], `typography.${k}`);
const size = (k) => need(ty(k).fontSize, `typography.${k}.fontSize`);
const c = fm.colors;
const sp = fm.spacing;
const px = (v) => String(v);
const ms = (v) => String(v);

// The "token: --display-hero: clamp(...)" string carries the declaration itself.
const heroTokenDecl = need(ty('hero').token, 'typography.hero.token').replace(/^--display-hero:\s*/, '');

const lines = [];
const L = (s = '') => lines.push(s);

L('/* GENERATED from DESIGN.md front-matter by scripts/tokens-from-design.mjs. Do not edit by hand. */');
L('/* Convenium values verbatim (D:\\Projects\\Convenium\\styles\\tokens.css). Portfolio additions are marked. */');
L(':root {');
L('  /* Font families: faces are declared in fonts.css, each with a metric-matched fallback. */');
L('  --font-family-display: "Archivo", "Archivo Fallback", "Arial Narrow", Arial, sans-serif;');
L('  --font-family-serif: "Newsreader", "Newsreader Fallback", Georgia, serif;');
L('  --font-family-ui: "Inter", "Inter Fallback", Arial, sans-serif;');
L();
L('  /* Palette. Cherry selects, maroon deepens, chili signals, chili-300 is red text on noir. */');
L(`  --color-noir: ${c.noir};`);
L(`  --color-cotton: ${c.cotton};`);
L(`  --color-paper: ${c.paper};`);
L(`  --color-ink: ${c.ink};`);
L(`  --color-gray: ${c.gray};`);
L(`  --color-gray-on-noir: ${c['gray-on-noir']};`);
L(`  --color-hairline: ${c.hairline};`);
L(`  --red-cherry: ${c.cherry};`);
L(`  --red-maroon: ${c.maroon};`);
L(`  --red-chili: ${c.chili};`);
L(`  --red-chili-300: ${c['chili-300']};`);
L('  --color-accent: var(--red-cherry);');
L('  --color-accent-on-noir: var(--red-chili-300);');
L('  --color-accent-deep: var(--red-maroon);');
L(`  --color-wordmark: ${c.wordmark};`);
L(`  --rule-on-noir: ${c['rule-on-noir']};`);
L(`  --scrim-type: ${c['scrim-type']};`);
L();
L('  /* Tracking */');
L(`  --tracking-label: ${fm.typography.nav.letterSpacing};`);
L(`  --tracking-meta: ${fm.typography.label.letterSpacing};`);
L('  --display-axes: "wght" 900, "wdth" 100;');
L();
L('  /* Type scale (every size carries a rem term, WCAG 1.4.4) */');
L(`  --display-hero: ${heroTokenDecl}; /* portfolio: fitted as min(token, container / ${ty('hero').advanceEm}) */`);
L(`  --hero-advance-em: ${ty('hero').advanceEm};`);
L(`  --footer-advance-em: ${ty('footer-wordmark').advanceEm};`);
L(`  --font-h1: ${size('h1')};`);
L(`  --font-display: ${size('display')};`);
L(`  --font-list: ${size('list')};`);
L(`  --font-figure: ${size('figure')};`);
L(`  --font-sector: ${size('index-sector')};`);
L(`  --font-card-title: ${size('card-title')};`);
L(`  --font-subhead: ${size('subhead')};`);
L(`  --font-body: ${size('body')};`);
L(`  --font-small: ${size('small')};`);
L(`  --font-label: ${size('label')};`);
L(`  --font-nav: ${size('nav')};`);
L();
L('  /* Spacing, base 8 */');
for (const [k, v] of Object.entries(sp.scale)) L(`  --space-${k}: ${px(v)};`);
L(`  --space-container: ${sp.container};`);
L(`  --sheet-inset: ${sp.sheetInset};`);
L(`  --gutter: ${sp.gutter};`);
L(`  --band-pad: ${sp.bandPad};`);
L(`  --measure-body: ${sp.measure.body};`);
L(`  --measure-lede: ${sp.measure.lede};`);
L(`  --measure-small: ${sp.measure.small};`);
L(`  --measure-label: ${sp.measure.label};`);
L(`  --touch-min: ${sp.touchTargetMin};`);
L(`  --row-work: ${sp.rowMin.workRow};`);
L(`  --row-role: ${sp.rowMin.roleRow};`);
L(`  --row-channel: ${sp.rowMin.channelRow};`);
L(`  --row-doc: ${sp.rowMin.docRow};`);
L();
L('  /* Radii */');
L(`  --radius-sheet: ${fm.rounded.sheet};`);
L(`  --radius-control: ${fm.rounded.control};`);
L(`  --radius-media: ${fm.rounded.media};`);
L(`  --radius-card: ${fm.rounded.card};`);
L(`  --radius-pill: ${fm.rounded.pill};`);
L();
L('  /* Motion: state feedback only. The three effects live in src/scripts and read motion.* from DESIGN.md. */');
L(`  --ease-out-sharp: ${fm.motion['css-ease-out']};`);
L(`  --ease-in-out: ${fm.motion['css-ease-in-out']};`);
L(`  --duration-nav-hover: ${ms(fm.motion.micro)};`);
L(`  --duration-nav-active: ${ms(fm.motion.active)};`);
L(`  --duration-reveal: ${ms(fm.motion.move)};`);
L(`  --duration-scene: ${ms(fm.motion.scene)};`);
L(`  --duration-menu: ${ms(fm.motion.menu)};`);
L();
L('  /* Hero (portfolio) */');
L(`  --runway-hero: ${fm.hero.runway};`);
L(`  --runway-hero-phone: ${fm.hero.runwayPhone};`);
L(`  --runway-hero-active: var(--runway-hero);`);
L(`  --sheet-overlap: ${fm.hero.sheetOverlap.desktop};`);
L(`  --enter-disc: ${parseInt(fm.hero.enterDisc, 10)}px;`);
L();
L('  /* Chrome (portfolio) */');
L(`  --header-h: ${fm.spacing.header.height};`);
L(`  --tabbar-h: ${fm.spacing.tabBar.height};`);
{ const fsz = String(fm.motion.floatSize).match(/(\d+)\s*x\s*(\d+)/); L(`  --float-w: ${fsz[1]}px;`);
L(`  --float-h: ${fsz[2]}px;`); }
L(`  --cursor-dot: ${fm.cursor.sizes.default};`);
L(`  --cursor-link: ${fm.cursor.sizes.link};`);
L(`  --cursor-view: ${fm.cursor.sizes.view};`);
L('  --ring-width: 2px;');
L('  --ring-offset: 3px;');
L('  --ring-ground: var(--color-noir);');
L('}');
L();
L('/* Phone rhythm: max-width 639px (Convenium phone rhythm) */');
L('@media (max-width: 639px) {');
L('  :root {');
L(`    --sheet-inset: 8px;`);
for (const [k, v] of Object.entries(sp.scalePhone)) L(`    --space-${k}: ${px(v)};`);
L('    --band-pad: 40px;');
L(`    --enter-disc: 72px;`);
L('  }');
L('}');
L();
L('/* The header slims below 960 */');
L('@media (max-width: 959px) {');
L('  :root {');
L(`    --header-h: ${fm.spacing.header.heightPhone};`);
L('  }');
L('}');
L();
L('/* Portrait viewports use the phone runway, whatever their width */');
L('@media (orientation: portrait) {');
L('  :root {');
L('    --runway-hero-active: var(--runway-hero-phone);');
L(`    --sheet-overlap: ${fm.hero.sheetOverlap.phone};`);
L('  }');
L('}');
L();

fs.mkdirSync(path.join(root, 'src/styles'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/styles/tokens.css'), lines.join('\n'));
console.log('tokens.css written, ' + lines.length + ' lines');
